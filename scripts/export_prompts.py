"""Write docs/prompts.md: the exact system prompt of the agents and every prompt_extra used in the configs.
usage (from the repository root): .sastlab/.venv/bin/python scripts/export_prompts.py"""
import glob, json, sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path.cwd()))
from sastlab.llm import SYSTEM, OPERATOR_HELP, system_prompt

extras = defaultdict(list)
for f in sorted(glob.glob("configs/*.json")):
    cfg = json.loads(Path(f).read_text())
    text = (cfg.get("llm") or {}).get("prompt_extra") or ""
    extras[text].append(Path(f).stem)
out = ["# Agent prompts", "",
       "Generated by `scripts/export_prompts.py`. The system prompt is built for each request from the base text below and the operator definitions; the list of available operators and the order of the definitions are shuffled for every request (the full campaigns `semgrep-v6` and `codeql-v6` used one fixed order of the definitions; the `*-promptfix` reruns use the shuffled one). The user message is the JSON observation of the strategy (diff to the seed, verdict, last 3 steps, available operators and, for strategy 5, the scanner diagnostics).", "",
       "## Base system prompt (original prompt)", "", "```", SYSTEM, "```", "", "## Operator definitions", ""]
out += [f"- `{name}`: {text}" for name, text in OPERATOR_HELP.items()]
# The literal_slice definition in the prompt is looser than the operator; the saved runs used it, so it stays and is noted.
out += ["", 'The definition of `literal_slice` is looser than the operator: the operator prefixes each SQL string literal with `#` and slices the prefix off (`"#SELECT ..."[1:]`), and does not split the literal. The saved runs used this wording unchanged.']
out += ["", "## Appended text (`llm.prompt_extra`)", ""]
for text, names in sorted(extras.items(), key=lambda kv: (kv[0] == "", kv[0])):
    if not text:
        out += [f"### No appended text (original prompt)", "", "Configs: " + ", ".join(f"`{n}`" for n in names), ""]
    else:
        out += ["### Appended text", "", "```", text, "```", "", "Configs: " + ", ".join(f"`{n}`" for n in names), ""]
Path("docs/prompts.md").write_text("\n".join(out))
print("wrote docs/prompts.md,", len(extras), "distinct appended texts")
