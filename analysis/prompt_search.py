"""Pysa search with an informed prompt and with free operator order (3 hard seeds x 15 streams, budget 15, qwen3-coder-next unless noted).
For each run and strategy: mean attempts to the first evasion (none counts as budget + 1), streams with an evasion, 95% bootstrap interval,
streams in which a candidate holds both ingredients (literal_slice and a sink-resolution rewrite), and the evading sets found.
Writes prompt_search.tex (rows) and prints the numbers. Reference rows come from the original run pysa-hard-qwen."""
import collections, json, random, statistics as st
from pathlib import Path
from _paths import RESULTS, OUT_DIR

R = RESULTS
OUT = OUT_DIR
NAMES = {1: "Random", 2: "Heuristic", 3: "History-only", 5: "Diagnostic"}
RUNS = [("pysa-hard-qwen", "Original"), ("pysa-hard-any", "Original prompt, any order"),
        ("pysa-hard-informed-noorder", "Tool-aware"), ("pysa-hard-informed", "Informed"), ("pysa-hard-informed-any", "Informed prompt, any order"),
        ("pysa-hard-informed-any-35b", "Informed prompt, any order, 35B model")]
SINK = {"dict_dispatch", "dynamic_sink"}


def cl(keys, vals):
    """Average the paired values of one stream (trajectory index) over the seeds, so that the unit of resampling is the stream, as stated in the method section."""
    g = collections.defaultdict(list)
    for k, v in zip(keys, vals):
        g[k[1]].append(v)
    return [st.mean(v) for _, v in sorted(g.items())]


def bootstrap(values, n=5000, seed=11):
    rng = random.Random(seed)
    means = sorted(st.mean(rng.choices(values, k=len(values))) for _ in range(n))
    return means[int(0.025 * n)], means[int(0.975 * n) - 1]


def sign_flip_p(diffs, n=5000, seed=5):
    rng = random.Random(seed)
    observed = abs(st.mean(diffs))
    return (sum(abs(st.mean(d * rng.choice((-1, 1)) for d in diffs)) >= observed - 1e-12 for _ in range(n)) + 1) / (n + 1)


def main():
    lines, summary, per_stream = [], {}, {}
    for run, label in RUNS:
        path = R / run / "attempts.jsonl"
        if not path.exists():
            continue
        manifest = json.loads((R / run / "manifest.json").read_text())
        rows = [json.loads(l) for l in path.read_text().splitlines() if l.strip()]
        budget = manifest["config"]["attempts"]
        errors = sum(r["scan"]["status"] != "ok" for r in rows)
        for s in sorted({r["strategy"] for r in rows}):
            if s not in NAMES:
                continue
            groups = collections.defaultdict(list)
            for r in rows:
                if r["strategy"] == s:
                    groups[(r["seed"], r["trajectory"])].append(r)
            if any(len(g) != budget for g in groups.values()):
                continue  # run unfinished
            firsts = [min([r["attempt"] for r in g if r["bypassed_rules"]] or [budget + 1]) for g in groups.values()]
            found = sum(f <= budget for f in firsts)
            both = sum(any("literal_slice" in r["operators"] for r in g) and any(set(r["operators"]) & SINK for r in g) for g in groups.values())
            both_in_one = sum(any("literal_slice" in r["operators"] and set(r["operators"]) & SINK for r in g) for g in groups.values())
            per_stream[(run, s)] = dict(zip(groups, firsts))
            size = [len(next(r for r in sorted(g, key=lambda r: r["attempt"]) if r["bypassed_rules"])["operators"]) for g in groups.values() if any(r["bypassed_rules"] for r in g)]
            lo, hi = bootstrap(cl(list(groups), firsts))
            sets = collections.Counter(tuple(sorted(r["operators"])) for g in groups.values() for r in g if r["bypassed_rules"])
            if "any" not in run and s in (3, 5):
                lines.append(f"{label} & {NAMES[s]} & {st.mean(firsts):.2f} [{lo:.2f}, {hi:.2f}] & {found}/{len(groups)} \\\\")
            summary[(run, s)] = dict(mean=st.mean(firsts), found=found, streams=len(groups), both_ingredients=both, both_in_one_candidate=both_in_one, errors=errors,
                                    evading_sets=sets.most_common(3), mean_size_of_first_evasion=(st.mean(size) if size else None))
    (OUT / "prompt_search.tex").write_text("% Generated by analysis/prompt_search.py -- do not edit.\n" + "\n".join(lines).rstrip("\\ ") + "\n")
    for k, v in summary.items():
        print(k, v)
    macros = {}
    key = {"pysa-hard-qwen": "Orig", "pysa-hard-informed-noorder": "NoOrd", "pysa-hard-informed": "Inf", "pysa-hard-any": "Any", "pysa-hard-informed-any": "InfAny", "pysa-hard-informed-any-35b": "InfAnyBig"}
    nm = {1: "Rand", 3: "Hist", 5: "Diag"}
    for (run, s), v in summary.items():
        if run in key and s in nm:
            macros[f"promptFound{key[run]}{nm[s]}"] = v["found"]; macros[f"promptMean{key[run]}{nm[s]}"] = f"{v['mean']:.2f}"
            if v["mean_size_of_first_evasion"]: macros[f"promptSize{key[run]}{nm[s]}"] = f"{v['mean_size_of_first_evasion']:.1f}"
    base = per_stream.get(("pysa-hard-qwen", 1)); heur = per_stream.get(("pysa-hard-qwen", 2))
    for (run, s), d in per_stream.items():
        for name, ref in (("random", base), ("heuristic", heur)):
            if ref and set(d) == set(ref) and not (run == "pysa-hard-qwen" and s in (1, 2)) and "any" not in run:
                x = [d[k] - ref[k] for k in sorted(d)]
                xs = cl(sorted(d), x)
                lo, hi = bootstrap(xs)
                print(f"paired {run} strategy {s} minus {name}: {st.mean(x):+.2f} [{lo:+.2f}, {hi:+.2f}] p={sign_flip_p(xs):.4f}")
                if run in ("pysa-hard-informed", "pysa-hard-informed-noorder") and s in (3, 5):
                    k = f"promptDiff{key[run]}{nm[s]}{name.capitalize()}"
                    p_ = sign_flip_p(xs)
                    macros[k] = f"{st.mean(x):+.2f}".replace("-", "$-$").replace("+", "$+$"); macros[k + "Ci"] = f"[{lo:+.2f}, {hi:+.2f}]".replace("-", "$-$").replace("+", "$+$")
                    macros[k + "P"] = "$<0.001$" if p_ < 0.001 else f"{p_:.3f}"
    (OUT / "prompt_search_numbers.tex").write_text("% Generated by analysis/prompt_search.py -- do not edit.\n" + "".join("\\newcommand{\\%s}{%s}\n" % (k, v) for k, v in macros.items()))


if __name__ == "__main__":
    main()
