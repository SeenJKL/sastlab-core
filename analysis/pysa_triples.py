"""Pysa on all subsets of up to 3 rewrites (16 rewrites, without the 2 round trips) on 3 seeds from the official suites (o03, o18, o24).
Writes pysa_triples_numbers.tex."""
import itertools, json
from pathlib import Path
from _paths import RESULTS, OUT_DIR

R = RESULTS / "pysa-triples"
OUT = OUT_DIR
HIDE = {"dict_dispatch", "dynamic_sink", "partial_sink", "methodcaller_sink", "unbound_sink"}
CONCAT = {"o18_semgrep"}                       # builds the query by concatenation among these 3 seeds
fmt = lambda n: f"{n:,}".replace(",", "{,}")

quals = {q["seed"]: q["qualifying_rules"] for q in json.loads((R / "qualifications.json").read_text())}
cand, invalid, errors, noneq = {}, 0, 0, 0
for line in (R / "evaluations.jsonl").read_text().splitlines():
    e = json.loads(line)
    if e["status"] != "evaluated":
        invalid += 1
        continue
    if e["scan_status"] != "ok":
        errors += 1
        continue
    if not e["equivalent"]:
        noneq += 1
        continue
    cand[(e["seed"], tuple(sorted(e["operators"])))] = not (set(quals[e["seed"]]) & set(e["scan_rules"]))
pairs = [k for k in cand if len(k[1]) == 2]; triples = [k for k in cand if len(k[1]) == 3]
silent_sub = lambda k: any(cand.get((k[0], tuple(sorted(c))), False) for n in (1, 2) for c in itertools.combinations(k[1], n))
new = [k for k in triples if cand[k] and not silent_sub(k)]
pred = lambda s, o: bool(set(o) & HIDE) and ("literal_slice" in o or ("format_swap" in o and s in CONCAT))
exc = [k for k, v in cand.items() if pred(*k) != v]
macros = dict(triSeeds=len(quals), triCand=fmt(len(cand)), triInvalid=fmt(invalid), triErrors=errors, triNotEquiv=noneq, triSilent=fmt(sum(cand.values())),
              triPairs=fmt(len(pairs)), triPairsSilent=sum(cand[k] for k in pairs), triTriples=fmt(len(triples)), triTriplesSilent=sum(cand[k] for k in triples),
              triNew=len(new), triExceptions=len(exc))
(OUT / "pysa_triples_numbers.tex").write_text("% Generated by analysis/pysa_triples.py -- do not edit.\n" + "".join("\\newcommand{\\%s}{%s}\n" % (k, v) for k, v in macros.items()))
print(macros)
