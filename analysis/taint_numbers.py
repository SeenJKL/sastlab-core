"""Semgrep in taint mode versus the pattern rule, and the pinned versus the newest Semgrep, on the main and official seeds.
Per rewrite: seeds on which that single rewrite evades. Taint: all candidates of the exhaustive runs (singles and pairs). Writes taint.tex
(rows) and taint_numbers.tex (macros)."""
import collections as C, json, sys
from pathlib import Path
from _paths import RESULTS, OUT_DIR

R = RESULTS
OUT = OUT_DIR
sys.path.insert(0, str(R.parent))
from sastlab.transforms import OPERATORS

CONCAT = {"o18_semgrep", "o23_codeql", "d01_concat", "d12_concat_parts"}   # seeds that build the query by concatenation
CORE = {"literal_slice", "extract_1", "extract_2"}
fmt = lambda n: f"{n:,}".replace(",", "{,}")


def load(run):
    d = R / run
    quals = {q["seed"]: q["qualifying_rules"] for q in json.loads((d / "qualifications.json").read_text())}
    cand, errors, noneq = {}, 0, 0
    for line in (d / "evaluations.jsonl").read_text().splitlines():
        e = json.loads(line)
        if e["status"] != "evaluated" or not quals[e["seed"]]:
            continue
        if e["scan_status"] != "ok":
            errors += 1
            continue
        if not e["equivalent"]:
            noneq += 1
            continue
        cand[(e["seed"], tuple(sorted(e["operators"])))] = bool(e["bypassed_rules"])
    return quals, cand, errors, noneq


def singles(cand):
    out = C.defaultdict(set)
    for (s, o), v in cand.items():
        if len(o) == 1 and v:
            out[o[0]].add(s)
    return out


def main():
    taint, pattern, latest = {}, {}, {}
    errs = noneq = 0
    q = {}
    for k in ("main", "official"):
        qq, c, e, n = load(f"semgrep-taint-{k}-pairs"); q.update(qq); taint.update(c); errs += e; noneq += n
        qq, c, *_ = load(f"semgrep-pattern-{k}-singles"); pattern.update(c)
        qq, c, *_ = load(f"semgrep-latest-{k}-singles"); latest.update(c)
    qq, c, e, n = load("semgrep-taint-real-pairs"); taint_real = c; errs += e; noneq += n
    qq, c, e, n = load("semgrep-taint-diverse-singles"); taint_div = c; errs += e; noneq += n
    shared = sorted({s for s, o in taint} & {s for s, o in pattern})          # qualified under both rules
    tq = sorted({s for s, o in taint})
    ts, ps, ls = singles(taint), singles(pattern), singles(latest)
    rows = []
    silent = []
    for op in OPERATORS:
        a_, b_ = len(ps.get(op, set()) & set(shared)), len(ts.get(op, set()) & set(shared))
        if a_ or b_:
            rows.append(f"{op.replace('_', chr(92) + '_')} & {a_} & {b_} \\\\")
        else:
            silent.append(op)
    rows.append(f"The other {len(silent)} rewrites & 0 & 0 \\\\")
    (OUT / "taint.tex").write_text("% Generated by analysis/taint_numbers.py -- do not edit.\n" + "\n".join(rows).rstrip("\\ ") + "\n")
    # structure of the taint rule over all candidates
    allt = {**taint, **taint_real, **taint_div}
    pred = lambda s, o: bool(set(o) & CORE) or ("format_swap" in o and s in CONCAT)
    exc = [k for k, v in allt.items() if pred(*k) != v]
    core_only = [k for k, v in allt.items() if bool(set(k[1]) & CORE) != v]
    # how the pattern rule's sink-resolution rewrites do under taint
    hide = {"dict_dispatch", "dynamic_sink", "partial_sink", "methodcaller_sink", "unbound_sink"}
    hide_taint = sum(len(ts.get(h, set()) & set(shared)) for h in hide); hide_pat = sum(len(ps.get(h, set()) & set(shared)) for h in hide)
    # pinned versus newest Semgrep on identical single-rewrite candidates
    both = [k for k in pattern if k in latest]
    diff = [k for k in both if pattern[k] != latest[k]]
    macros = dict(taintSeedsMain=sum(bool(v) for k, v in q.items() if k.startswith("seed")), taintSeedsOfficial=sum(bool(v) for k, v in q.items() if k.startswith("o")),
                  taintSeedsReal=len({s for s, o in taint_real}), taintSeedsDiverse=len({s for s, o in taint_div}), taintShared=len(shared),
                  taintCand=fmt(len(allt)), taintEvade=fmt(sum(allt.values())), taintErrors=errs, taintNotEquiv=noneq,
                  taintExceptions=len(exc), taintCoreExceptions=len(core_only), taintHideTaint=hide_taint, taintHidePattern=hide_pat,
                  taintHideTotal=len(shared) * len(hide), latestCompared=len(both), latestDifferent=len(diff))
    FLOW = {"dynamic_sink", "char_launder", "deep_nest", "db_roundtrip", "simplequeue_roundtrip", "pickle_roundtrip", "partial_sink", "methodcaller_sink", "unbound_sink"}
    cq, cq_seeds, cq_err = {}, set(), 0
    for k in ("main", "official"):
        qq, c, e, n = load(f"codeql-latest-{k}-singles"); cq.update(c); cq_seeds |= {s for s, v in qq.items() if v}; cq_err += e + n
    cq_exc = [k for k, v in cq.items() if (k[1][0] in FLOW) != v]
    macros.update(latestCqSeeds=len(cq_seeds), latestCqCand=len(cq), latestCqEvade=sum(cq.values()), latestCqExceptions=len(cq_exc), latestCqErrors=cq_err)
    qa, ca, ea, na = load("semgrep-taint-apps-pairs")
    exc_a = [k for k, v in ca.items() if (bool(set(k[1]) & CORE) or ("format_swap" in k[1] and k[0] in CONCAT)) != v]
    macros.update(taintAppsSeeds=sum(bool(v) for v in qa.values()), taintAppsCand=fmt(len(ca)), taintAppsEvade=fmt(sum(ca.values())), taintAppsExceptions=len(exc_a), taintAppsErrors=ea + na)
    (OUT / "taint_numbers.tex").write_text("% Generated by analysis/taint_numbers.py -- do not edit.\n" + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()) + "\n")
    print(macros); print("shared seeds", len(shared), "exceptions", exc[:4], "core-only exceptions", len(core_only), {o: C.Counter(k[0] for k in core_only if o in k[1]) for o in ("format_swap",)})
    print("pattern vs latest different:", diff[:6]); print("\n".join(rows))


if __name__ == "__main__":
    main()
