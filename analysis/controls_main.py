"""Pattern rule (Semgrep formatted-sql-query) against the 4 control rewrites.
1. results/semgrep-controls-main: all 15 non-empty subsets on the 15 main seeds (exhaustive, no search).
2. Every saved run of the pinned pattern rule on the main, varied and official programs (searches and exhaustive runs): distinct
   (seed, operator set) pairs built only from the controls, on the same scope as codeql_rule.py.
Writes controls_numbers.tex."""
import collections
import json
from pathlib import Path
from _paths import RESULTS, OUT_DIR

RESULTS = RESULTS
CONTROLS = {"rename", "format_swap", "literal_slice", "dead_padding"}

RUN = RESULTS / "semgrep-controls-main"
OUT = OUT_DIR / "controls_numbers.tex"
NAMES = ("rename", "format_swap", "literal_slice", "dead_padding")
rows = [json.loads(line) for line in (RUN / "evaluations.jsonl").read_text().splitlines()]
assert all(r["status"] == "evaluated" and r["equivalent"] and r["scan_status"] == "ok" for r in rows), "scan error or behavior difference"
by = collections.defaultdict(list)
for r in rows:
    by[r["mask"]].append(bool(r["bypassed_rules"]))
evading_subsets = [m for m, v in by.items() if any(v)]
for m in evading_subsets:
    assert all(by[m]), "a subset evades on some seeds only"
    assert (m >> 1 & 1) and (m >> 2 & 1), "an evading subset without format_swap and literal_slice"
assert all(any(r["bypassed_rules"] for r in rows if r["mask"] == m) == bool(m >> 1 & 1 and m >> 2 & 1) for m in by), "format_swap + literal_slice is not sufficient"
macros = {"ctrlMainTotal": len(rows), "ctrlMainEvade": sum(r["bypassed_rules"] != [] for r in rows),
          "ctrlMainSubsets": len(by), "ctrlMainEvadeSubsets": len(evading_subsets), "ctrlMainSeeds": len({r["seed"] for r in rows})}
# 2. all saved runs of the pinned pattern rule on the main, varied and official programs (the scope of codeql_rule.py, so that the
# counts can be set side by side): distinct (seed, operator set) pairs built only from the controls
def in_scope(seed):
    return seed.startswith(("seed_", "d", "o"))


verdict, every = {}, {}
for run in sorted(RESULTS.iterdir()):
    manifest = run / "manifest.json"
    if not manifest.exists():
        continue
    m = json.loads(manifest.read_text())
    identity, config = m.get("identity") or {}, m.get("config") or {}
    if (identity.get("engine") or config.get("engine")) != "semgrep" or (identity.get("target_rules") or config.get("target_rules")) != ["formatted-sql-query"]:
        continue
    if identity.get("scanner_version") not in (None, "1.178.0"):
        continue
    for name, kind in (("evaluations.jsonl", "e"), ("attempts.jsonl", "a")):
        if not (run / name).exists():
            continue
        for line in (run / name).read_text().splitlines():
            r = json.loads(line)
            ops = tuple(sorted(r.get("operators") or []))
            if not in_scope(r["seed"]):
                continue
            ok = (r["status"] == "evaluated" and r["equivalent"] and r["scan_status"] == "ok") if kind == "e" else \
                 (r["scan"]["status"] == "ok" and (r.get("oracle") or {}).get("equivalent"))
            if ok:
                every.setdefault((r["seed"], ops), set()).add(bool(r["bypassed_rules"]))
                if ops and set(ops) <= CONTROLS:
                    verdict.setdefault((r["seed"], ops), set()).add(bool(r["bypassed_rules"]))
assert all(len(v) == 1 for v in verdict.values()), "a candidate got 2 verdicts"
macros_every = {"semRuleDistinct": len(every), "semRuleInconsistent": sum(len(v) > 1 for v in every.values())}
evading = [k for k, v in verdict.items() if True in v]
macros.update(macros_every)
macros.update({"ctrlAllTotal": len(verdict), "ctrlAllEvade": len(evading),
               "ctrlAllNoSlice": sum("literal_slice" not in k[1] for k in evading)})
OUT.write_text("% Generated by analysis/controls_main.py -- do not edit.\n" + "".join("\\newcommand{\\%s}{%s}\n" % kv for kv in macros.items()))
print(macros, sorted(evading_subsets))
