"""Generate pysa.tex (per-rewrite comparison) and pysa_numbers.tex (macros used in the text)
from the saved Pysa, Semgrep and CodeQL exhaustive runs. Uses pysa_numbers.py."""
import collections as C, json, statistics, sys
from pathlib import Path
from _paths import OUT_DIR
sys.path.insert(0, str(Path(__file__).resolve().parent))
import pysa_numbers as P

OUT = OUT_DIR
sys.path.insert(0, str(P.R.parent))
from sastlab.transforms import OPERATORS

table, qual, errors, inequivalent = P.pysa_table()
cq, sg = P.other("codeql"), P.other("semgrep")
fmt = lambda n: f"{n:,}".replace(",", "{,}")
macros = {}


def m(name, value):
    macros[name] = value if isinstance(value, str) else fmt(value)


singles = {op: [(v["all"], v["f5005"], v["f5051"]) for (c, s, o), v in table.items() if o == (op,)] for op in OPERATORS}
rows = []
for op in OPERATORS:
    v = singles[op]
    cs = [x for (s, o), x in cq.items() if o == (op,)]
    ss = [x for (s, o), x in sg.items() if o == (op,)]
    rows.append(f"{op.replace('_', chr(92) + '_')} & {sum(ss)}/{len(ss)} & {sum(cs)}/{len(cs)} & {sum(x[1] for x in v)}/{len(v)} & "
                f"{sum(x[2] for x in v)}/{len(v)} & {sum(x[0] for x in v)}/{len(v)} \\\\")
# the last row has no row terminator: a terminator at the end of an input file before \bottomrule is a LaTeX error
body = "\n".join(rows).removesuffix("\\\\").rstrip()
(OUT / "pysa.tex").write_text("% Generated by analysis/pysa_tables.py -- do not edit.\n" + body + "\n")

pairs = {k: v for k, v in table.items() if len(k[2]) == 2}
RT = {"db_roundtrip", "simplequeue_roundtrip"}
SINK = {"dict_dispatch", "dynamic_sink", "methodcaller_sink", "partial_sink", "unbound_sink"}
n_single = sum(len(k[2]) == 1 for k in table)
m("pysaCandidates", len(table)); m("pysaSingles", n_single); m("pysaPairs", len(pairs))
m("pysaErrors", errors); m("pysaNotEquivalent", inequivalent)
for corpus, key in (("main", "Main"), ("varied", "Varied"), ("official", "Official")):
    seeds = qual[corpus]
    m(f"pysaSeeds{key}", len(seeds)); m(f"pysaQual{key}", sum(bool(r) for r in seeds.values()))
    assert all(len(r) in (0, 2) for r in seeds.values())
scan_seconds = []
for run in sum(P.PYSA_RUNS.values(), []):
    scan_seconds += [e["scan_seconds"] for e in P.S.rd(f"{run}/evaluations.jsonl") if e.get("scan_seconds")]
m("pysaScanSeconds", f"{statistics.mean(scan_seconds):.1f}")

rt1 = [v for (c, s, o), v in table.items() if len(o) == 1 and o[0] in RT]
m("pysaRtSingleSilent", sum(v["all"] for v in rt1)); m("pysaRtSingleTotal", len(rt1))
sk1 = [v for (c, s, o), v in table.items() if len(o) == 1 and o[0] in SINK]
m("pysaSinkFlowMissing", sum(v["f5005"] for v in sk1)); m("pysaSinkStringMissing", sum(v["f5051"] for v in sk1))
m("pysaSinkTotal", len(sk1))
ls1 = [v for (c, s, o), v in table.items() if o == ("literal_slice",)]
m("pysaLsStringMissing", sum(v["f5051"] for v in ls1)); m("pysaLsFlowMissing", sum(v["f5005"] for v in ls1)); m("pysaLsTotal", len(ls1))
silent1 = sorted({o[0] for (c, s, o), v in table.items() if len(o) == 1 and v["all"]})
assert silent1 == sorted(RT), silent1
other_single = [(o, v) for (c, s, o), v in table.items() if len(o) == 1 and o[0] not in RT and (v["f5005"] or v["f5051"])]
quiet = [op for op in OPERATORS if op not in RT | SINK | {"literal_slice"} and not any(x[1] or x[2] for x in singles[op])]
m("pysaNeverCount", len(quiet))

withrt = {k: v for k, v in pairs.items() if set(k[2]) & RT}
m("pysaPairsRtTotal", len(withrt)); m("pysaPairsRtSilent", sum(v["all"] for v in withrt.values()))
sink_ls = {k: v for k, v in pairs.items() if "literal_slice" in k[2] and set(k[2]) & SINK}
m("pysaPairsSinkLsTotal", len(sink_ls)); m("pysaPairsSinkLsSilent", sum(v["all"] for v in sink_ls.values()))
sink_fs = {k: v for k, v in pairs.items() if "format_swap" in k[2] and set(k[2]) & SINK}
m("pysaPairsSinkFsTotal", len(sink_fs)); m("pysaPairsSinkFsSilent", sum(v["all"] for v in sink_fs.values()))
m("pysaPairsSilent", sum(v["all"] for v in pairs.values()))
explained = set(withrt) | set(sink_ls) | {k for k, v in sink_fs.items() if v["all"]}
m("pysaPairsUnexplainedSilent", sum(1 for k, v in pairs.items() if v["all"] and k not in explained))
rest = {k: v for k, v in pairs.items() if k not in withrt and k not in sink_ls and k not in sink_fs}
m("pysaPairsRestTotal", len(rest)); m("pysaPairsRestSilent", sum(v["all"] for v in rest.values()))
emergent = sum(1 for (c, s, o), v in pairs.items() if v["all"] and not any(table.get((c, s, (x,)), {}).get("all") for x in o))
m("pysaPairsEmergent", emergent)
m("pysaPairsFiveOhFiveOneEmergent", sum(1 for (c, s, o), v in pairs.items() if v["f5051"] and not any(table[(c, s, (x,))]["f5051"] for x in o)))
fs_seeds = sorted({k[1] for k, v in pairs.items() if v["all"] and "format_swap" in k[2] and not set(k[2]) & RT})
m("pysaFsSeeds", len(fs_seeds))

CTRL = {"rename", "format_swap", "literal_slice", "dead_padding"}
ctl = [v for (c, s, o), v in table.items() if set(o) <= CTRL]
m("pysaControlTotal", len(ctl)); m("pysaControlSilent", sum(v["all"] for v in ctl))

RS = CTRL | {"extract_1", "extract_2", "branch_split"}
rs = [v for (c, s, o), v in table.items() if set(o) <= RS]
m("pysaRestructTotal", len(rs)); m("pysaRestructSilent", sum(v["all"] for v in rs)); m("pysaRestructFlow", sum(v["f5005"] for v in rs))

for name, ref, tag in (("CodeQL", cq, "Cq"), ("Semgrep", sg, "Sg")):
    tab = C.Counter()
    for (c, s, o), v in table.items():
        if (s, o) in ref:
            tab[(v["all"], ref[(s, o)])] += 1
    m(f"pysa{tag}Both", sum(tab.values())); m(f"pysa{tag}Detect", tab[(False, False)])
    m(f"pysa{tag}OnlyPysa", tab[(True, False)]); m(f"pysa{tag}OnlyOther", tab[(False, True)]); m(f"pysa{tag}Silent", tab[(True, True)])
(OUT / "pysa_numbers.tex").write_text("% Generated by analysis/pysa_tables.py -- do not edit.\n" +
                                      "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()) + "\n")
for k, v in macros.items():
    print(k, v)
