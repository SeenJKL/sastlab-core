"""Does the Pysa result depend on our source model? Compare the sets of firing rules of the runs with the stock source
(http.server.BaseHTTPRequestHandler.path through a handler method) with the runs that use our parameter model, on the same candidates.
Writes pysa_http_numbers.tex."""
import json
from pathlib import Path
from _paths import RESULTS, OUT_DIR

R = RESULTS
OUT = OUT_DIR
PAIRS = (("pysa-http-main-singles", "pysa-main-singles"), ("pysa-http-main-pairs-s01", "pysa-main-pairs"),
         ("pysa-http-official-pairs-o03", "pysa-official-pairs"))


def load(run):
    quals = {q["seed"]: q["qualifying_rules"] for q in json.loads((R / run / "qualifications.json").read_text())}
    out, errors = {}, 0
    for line in (R / run / "evaluations.jsonl").read_text().splitlines():
        r = json.loads(line)
        if r["status"] != "evaluated":
            continue
        if r["scan_status"] != "ok":
            errors += 1
            continue
        out[(r["seed"], tuple(sorted(r["operators"])))] = tuple(sorted(r["scan_rules"]))
    return quals, out, errors


total = same = errors = qual_diff = seeds = 0
for http, base in PAIRS:
    qh, dh, eh = load(http)
    qb, db, _ = load(base)
    shared = [k for k in dh if k in db]
    total += len(shared)
    same += sum(dh[k] == db[k] for k in shared)
    errors += eh
    qual_diff += sum(qh[s] != qb.get(s) for s in qh)
    seeds += len(qh)
fmt = lambda n: f"{n:,}".replace(",", "{,}")
(OUT / "pysa_http_numbers.tex").write_text("% Generated by analysis/http_robustness.py -- do not edit.\n" + "".join(
    f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in dict(pysaHttpCandidates=fmt(total), pysaHttpSame=fmt(same), pysaHttpErrors=errors,
                                                      pysaHttpQualDiff=qual_diff).items()))
print(total, same, errors, qual_diff)
