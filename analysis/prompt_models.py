"""Informed prompt on Pysa for 3 models and 2 sets of 3 seeds (increasing order, budget 15, 45 streams per cell).
Set A = the 3 hard seeds (main corpus); set B = o03, o18 and o24 from the official suites. Baselines: random and heuristic of the same set
(A: pysa-hard-qwen, B: pysa-hard2-informed). An attempt whose rewrite does not apply to the seed (format_swap on a % string) counts as a failed attempt for every strategy.
Writes prompt_models.tex and prints paired differences against random."""
import collections, json, random, statistics as st
from pathlib import Path
from _paths import RESULTS, OUT_DIR

R = RESULTS
OUT = OUT_DIR
CELLS = [("A", "coder", "pysa-hard-informed"), ("A", "35B", "pysa-hard-informed-35b"), ("A", "8B", "pysa-hard-informed-8b"),
         ("B", "coder", "pysa-hard2-informed"), ("B", "35B", "pysa-hard2-informed-35b")]
BASE = {"A": "pysa-hard-qwen", "B": "pysa-hard2-informed"}
AGENT = {3: "History-only", 5: "Diagnostic"}


def firsts(run, strategy):
    rows = [json.loads(l) for l in (R / run / "attempts.jsonl").read_text().splitlines() if l.strip()]
    budget = json.loads((R / run / "manifest.json").read_text())["config"]["attempts"]
    g = collections.defaultdict(list)
    for r in rows:
        if r["strategy"] == strategy:
            g[(r["seed"], r["trajectory"])].append(r)
    assert all(len(v) == budget for v in g.values()), run
    return {k: min([r["attempt"] for r in v if r["bypassed_rules"]] or [budget + 1]) for k, v in g.items()}, budget


def cl(keys, vals):
    """Average the paired values of one stream (trajectory index) over the seeds, so that the unit of resampling is the stream, as stated in the method section."""
    g = collections.defaultdict(list)
    for k, v in zip(keys, vals):
        g[k[1]].append(v)
    return [st.mean(v) for _, v in sorted(g.items())]


def boot(x, n=5000, seed=11):
    rng = random.Random(seed)
    m = sorted(st.mean(rng.choices(x, k=len(x))) for _ in range(n))
    return m[int(0.025 * n)], m[int(0.975 * n) - 1]


def p_flip(x, n=5000, seed=5):
    rng = random.Random(seed)
    o = abs(st.mean(x))
    return (sum(abs(st.mean(d * rng.choice((-1, 1)) for d in x)) >= o - 1e-12 for _ in range(n)) + 1) / (n + 1)


def sgn(v):
    return f"{v:+.2f}".replace("-", "$-$").replace("+", "$+$")


def main():
    lines, macros = [], {}
    for sset in ("A", "B"):
        rnd, b = firsts(BASE[sset], 1)
        heu, _ = firsts(BASE[sset], 2)
        lines.append(f"{sset} & Random & - & {st.mean(rnd.values()):.2f} & {sum(v <= b for v in rnd.values())}/{len(rnd)} & - & - \\\\")
        lines.append(f"{sset} & Heuristic & - & {st.mean(heu.values()):.2f} & {sum(v <= b for v in heu.values())}/{len(heu)} & {sgn(st.mean([heu[k] - rnd[k] for k in rnd]))} & {boot([heu[k] - rnd[k] for k in sorted(rnd)])[0]:+.2f} \\\\" if False else "")
        for s_, model, run in CELLS:
            if s_ != sset or not (R / run / "attempts.jsonl").exists():
                continue
            for s in (3, 5):
                f, _ = firsts(run, s)
                keys = sorted(rnd)
                d = [f[k] - rnd[k] for k in keys]
                lo, hi = boot(cl(keys, d))
                p = p_flip(cl(keys, d))
                lines.append(f"{sset} & {model} & {AGENT[s]} & {st.mean(f.values()):.2f} & {sum(v <= b for v in f.values())}/{len(f)} & {sgn(st.mean(d))} & [{sgn(lo)}, {sgn(hi)}] \\\\")
                mk = f"pm{sset}{ {'coder': 'Coder', '35b': 'Big', '8b': 'Eight'}[model.lower()] }{ {3: 'Hist', 5: 'Diag'}[s] }"
                macros.update({mk + "Diff": sgn(st.mean(d)), mk + "Ci": f"[{sgn(lo)}, {sgn(hi)}]", mk + "Found": sum(v <= b for v in f.values())})
                print(sset, model, AGENT[s], f"mean {st.mean(f.values()):.2f} found {sum(v <= b for v in f.values())}/{len(f)} vs random {st.mean(d):+.2f} [{lo:+.2f},{hi:+.2f}] p={p:.4f}")
    lines = [l for l in lines if l]
    (OUT / "prompt_models_numbers.tex").write_text("% Generated by analysis/prompt_models.py -- do not edit.\n" + "".join("\\newcommand{\\%s}{%s}\n" % (k, v) for k, v in macros.items()))
    (OUT / "prompt_models.tex").write_text("% Generated by analysis/prompt_models.py -- do not edit.\n" + "\n".join(lines).rstrip("\\ ") + "\n")


if __name__ == "__main__":
    main()
