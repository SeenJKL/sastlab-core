"""More streams and repeats for the agent comparison.
(a) CodeQL, seeds d01 to d03 (45 streams per cell): random and heuristic from codeql-more-base, 3 models with the original and the informed prompt.
(b) Repeats with 2 other base seeds (7001, 7002) of the informed-prompt runs on Pysa (3 hard seeds) and the Semgrep pattern rule, 3 models.
Writes more_streams.tex (CodeQL rows), repeats.tex (repeat rows) and more_numbers.tex (macros)."""
import collections, json, random, statistics as st
from pathlib import Path
from _paths import RESULTS, OUT_DIR

R = RESULTS
OUT = OUT_DIR
AG = {3: "History-only", 5: "Diagnostic"}
MD = {"8b": "8B", "qwen": "Coder", "q36": "35B", "coder": "Coder", "35b": "35B"}


def firsts(run, strategy):
    path = R / run / "attempts.jsonl"
    if not path.exists():
        return None, None
    budget = json.loads((R / run / "manifest.json").read_text())["config"]["attempts"]
    g = collections.defaultdict(list)
    for line in path.read_text().splitlines():
        r = json.loads(line)
        if r["strategy"] == strategy:
            g[(r["seed"], r["trajectory"])].append(r)
    if not g or any(len(v) != budget for v in g.values()):
        return None, budget
    return {k: min([r["attempt"] for r in v if r["bypassed_rules"]] or [budget + 1]) for k, v in g.items()}, budget


def boot(x, n=5000, seed=11):
    rng = random.Random(seed)
    m = sorted(st.mean(rng.choices(x, k=len(x))) for _ in range(n))
    return m[int(0.025 * n)], m[int(0.975 * n) - 1]


def sgn(v):
    return f"{v:+.2f}".replace("-", "$-$").replace("+", "$+$")


def cl(keys, vals):
    """Average the paired values of one stream (trajectory index, and run for repeats) over the seeds: the unit of resampling is the stream."""
    g = collections.defaultdict(list)
    for k, v in zip(keys, vals):
        g[k[1:]].append(v)
    return [st.mean(v) for _, v in sorted(g.items())]


def diff(f, rnd):
    ks = sorted(set(f) & set(rnd))
    d = [f[k] - rnd[k] for k in ks]
    lo, hi = boot(cl(ks, d))
    return st.mean(d), lo, hi, len(ks)


def main():
    macros, rows = {}, []
    # (a) CodeQL
    rnd, b = firsts("codeql-more-base", 1)
    heu, _ = firsts("codeql-more-base", 2)
    if rnd:
        rows.append(f"Random & - & - & {st.mean(rnd.values()):.2f} ({sum(v <= b for v in rnd.values())}/{len(rnd)}) & - \\\\")
        rows.append(f"Heuristic & - & - & {st.mean(heu.values()):.2f} ({sum(v <= b for v in heu.values())}/{len(heu)}) & {sgn(diff(heu, rnd)[0])} [{sgn(diff(heu, rnd)[1])}, {sgn(diff(heu, rnd)[2])}] \\\\")
        for prompt, tag in (("Original", "orig"), ("Informed", "informed")):
            for m in ("8b", "qwen", "q36"):
                for s in (3, 5):
                    f, _ = firsts(f"codeql-more-{tag}-{m}", s)
                    if not f:
                        continue
                    mean, lo, hi, n = diff(f, rnd)
                    rows.append(f"{MD[m]} & {AG[s]} & {prompt} & {st.mean(f.values()):.2f} ({sum(v <= b for v in f.values())}/{len(f)}) & {sgn(mean)} [{sgn(lo)}, {sgn(hi)}] \\\\")
        pass
    (OUT / "more_streams.tex").write_text("% Generated by analysis/more_streams.py -- do not edit.\n" + "\n".join(rows).rstrip("\\ ") + "\n")
    # (b) repeats: base seeds 6223 (original run), 7001, 7002
    rep_rows = []
    cells = {}
    for scanner, runs in (("Pysa", {6223: {"coder": "pysa-hard-informed", "35b": "pysa-hard-informed-35b", "8b": "pysa-hard-informed-8b"},
                                    7001: {m: f"pysa-rep1-{m}" for m in ("coder", "35b", "8b")}, 7002: {m: f"pysa-rep2-{m}" for m in ("coder", "35b", "8b")}}),
                          ("Pattern rule", {6223: {"coder": "semgrep-informed-qwen", "35b": "semgrep-informed-q36", "8b": "semgrep-informed-8b"},
                                            7001: {m: f"semgrep-rep1-{m}" for m in ("coder", "35b", "8b")}, 7002: {m: f"semgrep-rep2-{m}" for m in ("coder", "35b", "8b")}})):
        for seed, models in runs.items():
            if scanner == "Pysa":
                rnd_run = "pysa-hard-qwen" if seed == 6223 else f"pysa-rep{1 if seed == 7001 else 2}-coder"
            else:
                rnd_run = "semgrep-hard30" if seed == 6223 else f"semgrep-rep{1 if seed == 7001 else 2}-8b"
            r_, bb = firsts(rnd_run, 1)
            if not r_:
                continue
            for m, run in models.items():
                for s in (3, 5):
                    f, _ = firsts(run, s)
                    if not f:
                        continue
                    mean, lo, hi, n = diff(f, r_)
                    cells.setdefault((scanner, m, s), []).append((seed, st.mean(f.values()), sum(v <= bb for v in f.values()), len(f), mean, lo, hi))
    pooled_cells = {}
    for scanner, runs in (("Pysa", {6223: {"coder": "pysa-hard-informed", "35b": "pysa-hard-informed-35b", "8b": "pysa-hard-informed-8b"},
                                    7001: {m: f"pysa-rep1-{m}" for m in ("coder", "35b", "8b")}, 7002: {m: f"pysa-rep2-{m}" for m in ("coder", "35b", "8b")}}),
                          ("Pattern rule", {6223: {"coder": "semgrep-informed-qwen", "35b": "semgrep-informed-q36", "8b": "semgrep-informed-8b"},
                                            7001: {m: f"semgrep-rep1-{m}" for m in ("coder", "35b", "8b")}, 7002: {m: f"semgrep-rep2-{m}" for m in ("coder", "35b", "8b")}})):
        for seed, models in runs.items():
            rnd_run = ("pysa-hard-qwen" if seed == 6223 else f"pysa-rep{1 if seed == 7001 else 2}-coder") if scanner == "Pysa" else ("semgrep-hard30" if seed == 6223 else f"semgrep-rep{1 if seed == 7001 else 2}-8b")
            r_, bb = firsts(rnd_run, 1)
            if not r_:
                continue
            for m, run in models.items():
                for s in (3, 5):
                    f, _ = firsts(run, s)
                    if not f:
                        continue
                    ks = sorted(set(f) & set(r_))
                    pooled_cells.setdefault((scanner, m, s), {"d": [], "found": [], "n": [], "keys": []})
                    pooled_cells[(scanner, m, s)]["d"].append([f[k] - r_[k] for k in ks])
                    pooled_cells[(scanner, m, s)]["keys"].append([(k[0], k[1], seed) for k in ks])
                    pooled_cells[(scanner, m, s)]["found"].append(sum(f[k] <= bb for k in ks)); pooled_cells[(scanner, m, s)]["n"].append(len(ks))
    key = {"Pysa": "Pysa", "Pattern rule": "Pat"}
    for (scanner, m, s), v in sorted(pooled_cells.items()):
        allv = [x for d in v["d"] for x in d]
        allk = [k for ks in v["keys"] for k in ks]
        lo, hi = boot(cl(allk, allv))
        per = " & ".join(f"{sgn(st.mean(d))}" for d in v["d"])
        better = sum(boot(cl(ks, d))[1] < 0 for ks, d in zip(v["keys"], v["d"]))
        rep_rows.append(f"{scanner} & {MD[m]} & {AG[s]} & {per} & {sgn(st.mean(allv))} [{sgn(lo)}, {sgn(hi)}] & {better}/{len(v['d'])} \\\\")
        k = f"rep{key[scanner]}{ {'8B': 'Eight', 'Coder': 'Coder', '35B': 'Big'}[MD[m]] }{ {3: 'Hist', 5: 'Diag'}[s] }"
        macros.update({k + "Diff": sgn(st.mean(allv)), k + "Ci": f"[{sgn(lo)}, {sgn(hi)}]", k + "Better": better, k + "Reps": len(v["d"]), k + "Found": "/".join(str(x) for x in v["found"])})
        print(scanner, MD[m], AG[s], "per-run", [round(st.mean(d), 2) for d in v["d"]], "pooled", round(st.mean(allv), 2), (round(lo, 2), round(hi, 2)), "runs with interval below 0:", better, "found", v["found"])
    (OUT / "repeats_pysa.tex").write_text("% Generated by analysis/more_streams.py -- do not edit.\n" + "\n".join(l.split(" & ", 1)[1] for l in rep_rows if l.startswith("Pysa")).rstrip("\\ ") + "\n")
    (OUT / "repeats.tex").write_text("% Generated by analysis/more_streams.py -- do not edit.\n" + "\n".join(rep_rows).rstrip("\\ ") + "\n")
    (OUT / "more_numbers.tex").write_text("% Generated by analysis/more_streams.py -- do not edit.\n" + "".join("\\newcommand{\\%s}{%s}\n" % (k, v) for k, v in macros.items()))
    print("\n".join(rows))


if __name__ == "__main__":
    main()
